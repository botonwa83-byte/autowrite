import Foundation

/// Apex 系列与 Top 系列共用的家族宣传语。
///
/// 三条主张对应原始诉求：AI 解构学习 → 离线学习守住专注 → 小学到高中全学科覆盖。
/// 文案统一放在这里而不是散进各个产品资料，改一处即可让两个教育系列同步生效；
/// 也避免每次生成内容时重复手写，保证不同产品对外口径一致。
enum SeriesCampaignCopy {
    /// 主标语：用于开场、封面与口播首句。
    static let slogan = "让 AI 拆开学习的黑箱，把专注还给书桌"

    /// 副标语：补充可信度与覆盖范围。
    static let subSlogan = "离线就能学 · 小学到高中全学科 · 官方自研免费"

    /// 三条主张，正文按「主张 + 展开」成对呈现。
    static let pillars: [(title: String, detail: String)] = [
        (
            "AI 拆解知识的黑箱",
            "难的不是题，是不知道劲往哪使。我们把每个知识点拆开：它难在哪、卡在哪一步、下一步该练什么——知识一旦被拆开，就变得轻松、有趣、好懂，学习不再是撞运气。"
        ),
        (
            "离线学习，把注意力抢回来",
            "不靠网络续命，就没有推送、没有红点、没有「再看一条」。刷屏的手停下来，钻研的门才打得开——把时间从信息流里拿回来，还给真正值得解的那道题。"
        ),
        (
            "小学到高中，一族走完",
            "语文、数学、英语、物理、化学、生物、政治、历史、地理全线覆盖，一个产品家族陪你走完整个基础教育阶段，把精力投向方法本身。"
        )
    ]

    /// 短版口号：视频口播与图片封面用，一句话说完三条主张。
    static let shortHook = "AI 拆开学习的黑箱，让知识变得轻松有趣；离线就能学，把刷屏的手收回来，把精力投向方法。"

    /// 正文段落：按「主标语 → 副标语 → 三条主张」拼接，供生成器直接插入。
    static var message: String {
        let body = pillars.map { "· \($0.title)：\($0.detail)" }.joined(separator: "\n")
        return "\(slogan)\n\(subSlogan)\n\n\(body)"
    }
}
